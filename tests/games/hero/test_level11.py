def test_every_old_census_row_is_still_honoured():
    """The superseded census, row for row: each is shipped at its own x, with
    the kind and row the live ROM draws (SHIPPED_AS) - and for the movers the
    census's row is one frame of the bob, inside the shipped box."""
    lanterns = {(r, x, y) for r, x, y in HL.LANTERNS[L - 1]}
    got = shipped()
    for row in OLD_CENSUS:
        room, what, x, y = row
        if what == "lantern":
            assert (room, x, y) in lanterns
            continue
        what, sx, sy = SHIPPED_AS.get(row, (what, x, y))
        assert sx == x
        assert (room, what, sx, sy) in got, f"{what} {room} {sx},{sy} missing"
        if what in ("bat", "spider_free"):
            assert sy <= y <= sy + 7 + 11
        else:
            assert abs(sy - y) <= 1


def test_the_entities_the_old_census_never_saw():
    got = shipped()
    lanterns = {(r, x, y) for r, x, y in HL.LANTERNS[L - 1]}
    n = sum(1 for _r, w, _x, _y in OLD_CENSUS if w != "lantern")
    for room, entities in NOT_IN_CENSUS.items():
        for what, x, y in entities:
            if what == "miner":
                assert HL.MINER_POS[L - 1] == (room, x, y)
            elif what == "lantern":
                assert (room, x, y) in lanterns
            else:
                assert (room, what, x, y) in got, f"room {room} {what} missing"
                n += 1
    assert n == len(HL.SPIDERS[L - 1]) == 25, "a creature is in neither table"


