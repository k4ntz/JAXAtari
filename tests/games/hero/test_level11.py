def test_the_liquid_is_the_roms_colour_not_the_level_files():
    """The level file says #2d32b8. The ROM paints (162, 98, 33) on the water
    rows of every liquid room, and nothing else in the cave in that colour;
    the playthrough's water rows read (150, 98, 45) through the JPEG."""
    palette, rooms = common.level_data(L)
    liquid = common.rgb("#a26221")
