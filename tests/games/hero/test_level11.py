def test_room_0_paints_the_levels_own_blue():
    """The ROM leaves level 1's brown palette in place on room 0 until the
    first transition; the capture recolours it onto level 11's blue ramp,
    so room 0 must paint the blue shades and none of the brown."""
    _palette, rooms = common.level_data(L)
    for role in ("dark", "mid", "light"):
        r, g, b = common.rgb(HL.SHADES[L][role])
        assert (rooms[0] == np.array([r, g, b])).all(axis=-1).any(), (
            f"room 0 never paints its {role}")
