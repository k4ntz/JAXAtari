"""Level 4, against the corrected ROM reference.

The block in hero_levels.py is generated by tools/hero_gen/build_level.py,
which walks the level through the game's own room-transition code, captures
each room off the real ROM and refuses to emit anything unless the capture
agrees with the reference cell for cell. These tests re-check that agreement
from the committed data alone (no ale-py), then play the level.

Before the regeneration `level_images/tools/check_level.py 4` matched 1 of
the 8 rooms: the first capture pass kept ROOM 0's corridor band for every
room, so rooms 1-7 all carried room 0's pillar at x 60-67 and none of their
own.

Level 4 is the first level with two things earlier levels never had, and
each of them changed the generator:

  * SNAKES, in rooms 3 and 7. The ROM draws a snake in its own green
    whatever the cave's hue, wriggling inside a 7x7 box planted against a
    wall's side. It classified as a spider before - its body is 7 px wide
    too - so it came out kind 0, on a spider's clock, laser-killable, with
    bestiary.json's grey 5x11 bitmap and a kill box six rows below the
    sprite. See test_the_two_snakes_* below.
  * A PAIR OF ROOMS THAT DRAW THE SAME BAND. Rooms 5 and 6 draw the identical
    corridor, each with a two-cell pillar at cells 9-10. The generator used
    to call that one physical wall. Measured on the ROM it is not, and that
    is what test_the_two_identical_pillars_are_two_walls records.

The route, room by room:

    room 0  spawn in the left corridor, blocked by the pillar at x 60-67
            whose ceiling is the same pillar, so it cannot be flown over
            -> plant a stick, run, +75, then down the hole at x 72-87
    room 1  open corridor, holes at x 20-27 and x 136-143
    room 2  a twenty-cell corridor slab splits the room in two, and each
            half has both a ceiling entry and a floor hole of its own
    room 3  the same shape again, plus the first snake at x 112
    room 4  pillar at x 92-99 and one hole at x 72-87, on the pillar's left
            - free from room 3's left hole, a blast from its right one
    room 5  pillar at x 44-51, holes at x 20-27 and x 136-143; the right
            hole is on the entry side, so nothing has to be blasted
    room 6  the same corridor as room 5, but its floor hole is at x 60-95,
            so entering on the left means blasting the pillar
    room 7  the miner's room: solid flooded floor, a snake, and the miner
            at x 128
"""
