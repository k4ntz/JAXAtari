# --- the walls --------------------------------------------------------------
# Where to start for each wall, which way to walk into it and which way to
# run afterwards. None of it is a free choice: walk at a wall across a floor
# hole and the hero drops through the hole instead, so each start has to be
# on the wall's own stretch of solid floor.
#
#   room 0  pillar x 60-67, floor solid from x 8 to 71, but its cave wall is
#           THREE cells - x 8-19 - so the first column he fits in is x 20,
#           where levels 1-3 all start at x 16    -> walk right from 24
#   room 4  pillar x 92-99, floor solid from x 88 to 159, cave wall from
#           x 140                                        -> walk left from 132
#   room 5  pillar x 44-51, floor solid from x 28 to 135 -> walk left from 100
#   room 6  pillar x 44-51, floor hole at x 60-95, so the right-hand approach
#           would drop him in                            -> walk right from 16
APPROACH = {
    (0, 60): (24, RIGHT, LEFT),
    (4, 92): (132, LEFT, RIGHT),
    (5, 44): (100, LEFT, RIGHT),
    (6, 44): (16, RIGHT, LEFT),
}


def _renderer(env):
    from jaxatari.games.jax_hero import HeroRenderer
    return HeroRenderer(env.consts)


def _state_in(env, room):
    _, s = env.reset()
    return s.replace(level=np.int32(L - 1), room=np.int32(room))


def _wall_w(room, x):
    return next(z[3] for z in HL.DESTRUCTIBLE[L - 1]
                if z[0] == room and z[1] == x)


def _plant_against(env, room, x):
    """Walk up to the wall at `x`, plant a stick, run, and wait out the fuse."""
    c = env.consts
    from_x, towards, away = APPROACH[(room, x)]
    _, s = env.reset()
    s = s.replace(level=np.int32(L - 1), room=np.int32(room),
                  spider_alive=np.zeros_like(s.spider_alive),
                  player_x=np.int32(from_x), player_y=np.int32(75))
    for _ in range(80):
        _, s, _, _, _ = env.step(s, towards)
    flush = x - c.player_width if towards == RIGHT else x + _wall_w(room, x)
    assert int(s.player_x) == flush, \
        f"room {room}: he should stop flush against the wall at x {x}"
    _, s, _, _, _ = env.step(s, DOWN)
    assert bool(s.dyn_active), f"room {room}: a stick goes down on solid ground"
    for _ in range(30):
        _, s, _, _, _ = env.step(s, away)
    for _ in range(c.dyn_fuse_playable + 6):
        _, s, _, _, _ = env.step(s, NOOP)
    return s


def test_each_of_the_four_walls_pays_its_own_seventy_five(env):
    """Four walls, four separate blasts, 75 each - including rooms 5 and 6,
    whose pillars are drawn identically and used to be one shared wall."""
    c = env.consts
    for slot, (room, x, *_rest) in enumerate(HL.DESTRUCTIBLE[L - 1]):
        s = _plant_against(env, room, x)
        assert int(s.wall_stage[slot]) == 2, f"room {room}'s wall at x {x} must go"
        assert int(s.score) == c.wall_points == 75, \
            "one wall, one payment - none of them is shared"
        assert int(s.lives) == c.starting_lives, f"room {room}: fled in time"
        others = [i for i in range(len(HL.DESTRUCTIBLE[L - 1])) if i != slot]
        assert all(int(s.wall_stage[i]) == 0 for i in others), \
            "blasting one of them must not clear the others"


def test_room_0s_pillar_blocks_the_way_down_until_it_is_blasted(env):
    _, s = env.reset()
    s = s.replace(level=np.int32(L - 1), room=np.int32(0),
                  player_x=np.int32(24), player_y=np.int32(75))
    for _ in range(120):                              # keep pushing right
        _, s, _, _, _ = env.step(s, RIGHT)
    assert int(s.room) == 0, "no way past the pillar without dynamite"

    s = _plant_against(env, 0, 60)
    for _ in range(60):
        _, s, _, _, _ = env.step(s, RIGHT)
        if int(s.player_x) >= 76:
            break
    for _ in range(90):
        _, s, _, _, _ = env.step(s, NOOP)
        if int(s.room) == 1:
            break
    assert int(s.room) == 1, "the floor hole at x 72-87 leads to room 1"
