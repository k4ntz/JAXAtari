def test_still_creatures_are_still_and_only_the_bat_patrols(env):
    """Measured off the ROM with the hero parked out of the picture, 480
    frames of each room. Whether a creature moves is a property of the room:
    four of this level's six spiders never move at all, two bob 9 px over 64
    frames, and only the bat sweeps sideways - 22 px over 184 frames, on a
    different clock from its own 64-frame bob."""
    c = env.consts
    assert {k: v for k, v in HL.CREATURE_PATROL.items()
            if k[0] == L} == {(L, 4): 92}, "only the bat sweeps sideways"
    _, s = env.reset()
    s = s.replace(level=np.int32(L - 1))   # reset() starts on level 1's roster
    seen = [(set(), set()) for _ in HL.SPIDERS[L - 1]]
    for step in range(480):
        x, y = env._spider_pos(s.replace(step_counter=np.int32(step)))
        for i in range(len(seen)):
            seen[i][0].add(int(x[i]))
            seen[i][1].add(int(y[i]))

    still = [0, 2, 3, 5, 7, 8]          # four spiders and both snakes
    for i in still:
        _room, sx, sy, _p, _k = HL.SPIDERS[L - 1][i]
        assert seen[i] == ({sx}, {sy}), f"creature {i} hangs dead still"

    for i in (1, 6):                    # the two bobbing spiders
        sx, sy = HL.SPIDERS[L - 1][i][1], HL.SPIDERS[L - 1][i][2]
        assert seen[i][0] == {sx}, "a bobbing spider never moves sideways"
        assert (min(seen[i][1]), max(seen[i][1])) == (sy, sy + 9), "9 px of bob"
        assert int(c.SPIDER_BOB_HALF[L - 1, i]) == 32, "over 64 frames"

    xs, ys = seen[4]                    # the bat
    centre, patrol = HL.SPIDERS[L - 1][4][1], HL.SPIDERS[L - 1][4][3]
    assert (min(xs), max(xs)) == (centre - patrol, centre + patrol)
    assert max(xs) - min(xs) == 22, "22 px of patrol"
    assert max(ys) - min(ys) == 7, "and 7 of bob"
    assert int(c.SPIDER_PATROL_HALF[L - 1, 4]) == 92, "a 184-frame sweep"
    assert int(c.SPIDER_BOB_HALF[L - 1, 4]) == 32, "on a 64-frame bob"


