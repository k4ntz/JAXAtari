def _settle(env, s, budget=200):
    """Let him fall to the floor of the room he has just entered.

    He arrives at y = -3, above the ceiling band, and UP there lifts him
    straight back out of the top of the room, so nothing may steer until he
    is down."""
    room = int(s.room)
    for _ in range(budget):
        if int(s.player_y) > 60 and float(s.player_vy) == 0.0:
            return s
        _, s, _, _, _ = env.step(s, NOOP)
        if int(s.room) != room:
            return s
    return s


def _go(env, s, target, air):
    """Cross the room to `target`, flying if `air` and walking if not."""
    s = _settle(env, s)
    room = int(s.room)
    for _ in range(600):
        x = int(s.player_x)
        if x == target:
            return s
        if air:
            a = 6 if x < target else 7            # UPRIGHT / UPLEFT
        else:
            a = 8 if x < target else 9            # RIGHTFIRE / LEFTFIRE
        _, s, _, _, _ = env.step(s, a)
        if int(s.room) != room:
            return s
    return s


def _fall(env, s, budget=300):
    room = int(s.room)
    for _ in range(budget):
        _, s, _, _, _ = env.step(s, NOOP)
        if int(s.room) != room:
            return s
    return s


def test_level_5_can_be_played_from_the_spawn_to_the_miner(env):
    """The whole level, on the real engine, without losing a life.

    This is the check the level block could not pass before the side exit was
    measured: room 1 has no hole and nothing blastable, so the route simply
    stopped there.
    """
    import jax.numpy as jnp
    c = env.consts
    _, s = env.reset()
    s = s.replace(level=jnp.int32(L - 1))
    assert int(s.room) == 0 and int(s.lives) == c.starting_lives

    # room 0: blast the pillar at x 60-67, fly over the rubble, drop at x 78
    for _ in range(40):
        _, s, _, _, _ = env.step(s, RIGHT)
    _, s, _, _, _ = env.step(s, DOWN)
    assert bool(s.dyn_active), "a stick goes down on solid ground"
    for _ in range(30):
        _, s, _, _, _ = env.step(s, LEFT)
    for _ in range(c.dyn_fuse_playable + 8):
        _, s, _, _, _ = env.step(s, NOOP)
    assert int(s.score) == c.wall_points, "the pillar pays 75"
    s = _fall(env, _go(env, s, 78, air=True))
    assert int(s.room) == 1

    # room 1: shoot the bat, then walk out of the open LEFT edge
    s = _settle(env, s)
    for _ in range(400):
        # the bolt only reaches 23 px and LEFTFIRE walks him left as it fires,
        # so step back right whenever he drifts inside the bat's box
        _, s, _, _, _ = env.step(s, 8 if int(s.player_x) < 54 else 9)
        if not bool(s.spider_alive[0]):
            break
    assert not bool(s.spider_alive[0]), "the bat of room 1 can be shot"
    for _ in range(300):
        _, s, _, _, _ = env.step(s, LEFT)
        if int(s.room) != 1:
            break
    assert int(s.room) == 2, "room 1 is left through its left edge"

    # rooms 2-6: cross to the hole that lands him somewhere survivable
    #   2 -> x 78, so he drops through room 3's safe corridor (magma either
    #        side of x 48-111) and straight on through its hole at x 76-83
    #   4 -> x 130 (hole at x 128-135), 5 -> x 78, 6 -> x 114
    for room, target, air in ((2, 78, True), (4, 130, False),
                              (5, 78, False), (6, 114, False)):
        assert int(s.room) == room
        s = _fall(env, _go(env, s, target, air))
        if room == 2:
            assert int(s.room) == 3
            s = _fall(env, s)               # room 3 is fallen straight through
    assert int(s.room) == 7

    # room 7: walk to the miner at x 128
    s = _settle(env, s)
    for _ in range(400):
        _, s, _, _, _ = env.step(s, 8 if int(s.player_x) < 126 else NOOP)
        if int(s.level) != L - 1:
            break
    assert int(s.level) == L, "rescuing the miner advances to level 6"
    assert int(s.lives) == c.starting_lives, "and it costs no lives"
    assert int(s.score) > 1000 + c.wall_points


