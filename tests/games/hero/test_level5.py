def test_the_snake_is_a_snake_and_stretches_out_of_the_rock(env):
    """The snake in room 4 is kind 3, not a spider: the ROM draws it green
    whatever the cave's hue, anchored in the rock at x 127 and stretching
    rightwards out of it on the 64-frame cycle measured on level 4.

    This one is planted in an EIGHT pixel corridor (x 128-135, rock either
    side), so at full stretch it very nearly seals the gap and the way past
    it is the 8 frames in every 64 it spends pulled in. That only works
    because its box is what it is drawn in - see
    tests/games/hero/test_level4.py::test_a_snake_inside_the_rock_*.
    """
    from jaxatari.games.jax_hero import _snake_length
    slot = next(i for i, (*_r, k) in enumerate(HL.SPIDERS[L - 1]) if k == 3)
    room, x, y, patrol, _kind = HL.SPIDERS[L - 1][slot]
    assert (room, x, y, patrol) == (4, 128, 111, 0)
    assert int(env.consts.SPIDER_KIND[L - 1, slot]) == 3

    bg = HL.decode_bg(HL.BG_RLE_L5[room], HL.PALETTE_L5)
    solid = np.any(bg > 16, axis=-1)
    mid = y + 3
    assert solid[mid, x - 1], "anchored in the rock to its left"
    assert not solid[mid, x], "and drawn into the open corridor"
    assert solid[mid, x + 8], "an eight-pixel gap, all but sealed at full stretch"

    seen = {int(_snake_length(np.int32(t))) for t in range(64)}
    assert seen == set(range(8)), "every length from pulled in to 7 px out"


