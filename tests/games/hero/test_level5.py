"""Level 5, against the corrected ROM reference.

The block in hero_levels.py is generated by tools/hero_gen/build_level.py,
which walks the level through the game's own room-transition code, captures
each room off the real ROM and refuses to emit anything unless the capture
agrees with the reference cell for cell. These tests re-check that agreement
from the committed data alone (no ale-py), then play the level.

Level 5 is the level that made the walker honest. Before this, the ROM walk
reached two of its eight rooms and stopped, and `CORRECTIONS.md` recorded
level 5 among the ones that "stop very early" and put it down to a sealed
floor. The floor of room 1 is sealed - but the room is not a dead end, and
three separate things had to be measured before the ROM would give up the
rest of the level:

  * A ROOM IS ALSO LEFT SIDEWAYS. Room 1's corridor reaches the LEFT edge of
    the screen as open air, and walking into that edge runs the same
    transition code a fall does. Measured: off x 13 of room 1 the hero
    arrives in room 2 at x 148, and back off x 146 of room 2 he arrives in
    room 1 at x 16 - so a left edge leads down the chain and a right edge
    back up it, mirroring the floor and the ceiling. Rooms 2-7 had been read
    off the recorded video until this was found.
  * A TWO-CELL HOLE IS 8 PX WIDE and so is the hero. Aiming the descent at a
    cell edge misses it more often than not: room 3 refused both of its
    cells for 700 frames each and went through at x 78, between them.
  * READING A ROOM CAN MOVE THE HERO OUT OF IT. The reader parks him at RAM
    x = 0 so his sprite sits in the column strip the Atari never draws; in a
    room with a side exit the ROM reads x < 16 as "he has left" and
    transitions, so room 2 was being read as room 3.

What the ROM then said that the video had got wrong, in seven bands: four
`?` cells the video could not call (rooms 3, 4, 5 and 6, all of them `.`),
and three corridors the video read as plain rock and the ROM draws as MAGMA
(rooms 3, 5 and 6). hero_rooms.py was corrected from the walk.

The route, room by room:

    room 0  spawn in the left corridor, blocked by the pillar at x 60-67
            whose ceiling is the same pillar -> plant a stick, run, +75,
            then down the hole at x 72-87
    room 1  no hole anywhere in the floor and magma in the last two cells:
            walk LEFT off the open edge into room 2
    room 2  arrive at the right; a still spider hangs at x 76 and a bat
            patrols the floor band; the floor is open from x 24 to x 135
    room 3  magma down both sides of the corridor, safe from x 48 to x 111,
            hole at x 76-83
    room 4  a bat on the left, a snake on the floor at x 128, holes at
            x 24-31 and x 128-135
    room 5  magma at both edges and a magma pillar at x 48, hole at x 72-87
    room 6  the same again with the pillar at x 56, a still spider at
            x 112, holes at x 40-47 and x 112-119
    room 7  the miner's room: no hole, a flooded floor, a bat overhead and
            the miner at x 128
"""
