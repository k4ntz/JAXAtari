"""Level 15, against the corrected ROM reference.

The block in hero_levels.py is generated by a level builder that walks
the level through the game's own room-transition code, captures
each room off the real ROM and refuses to emit anything unless the capture
agrees with the reference cell for cell. These tests re-check that agreement
from the committed data alone (no ale-py), and check the engine draws it.

What came out of level 15:

  * THE WALK REACHES ALL SIXTEEN ROOMS. The old reference had it at 11 (rooms
    0-10); the walker's side exits carried it through rooms 11-15. The eleven
    rooms the reference already had were confirmed by the ROM unchanged.
  * THE OLD BLOCK WAS A PLACEHOLDER built on the superseded reference: one
    spider, one lantern, no magma, the miner at x 23. Every table is new.
  * ROOM 9's GAP BREATHES MAGMA (HL.MAGMA_MOUTHS), exactly like level 14 room
    5's: the eight air cells 14-21 between its magma walls close one cell per
    side every 8 frames and open again, 64-frame cycle from room entry,
    measured frame by frame with the hero alive above the picture. The one
    way down (the floor hole at 16-19) is under it.
  * ITS CREATURES RUN AT LEVEL 10'S SPEED: six bats sweep 22 px on 92 frames,
    everything that bobs bobs 7 px on 32; bats hold a wing pose 4 frames,
    spiders 8. The five hanging spiders are still. Five wall snakes stretch a
    pixel every 2 frames (32-frame cycle), timed on the ROM - room 12 has no
    park above the picture, so its two were timed from an on-screen park.
  * THE LIQUID IS BROWN, #a26221, not the #2d32b8 the level file gives (that
    column is a generated cycle, not a measurement): the ROM paints (162, 98,
    33) on the water rows of rooms 10-15. Room 14 has no water; the brown is
    the background of its wavy trim on rows 139-141, under a solid floor.
  * The census had 12 entities; the capture has 33. Two census
    rows are wrong: room 4's "still bat at y 110" patrols at y 103, and room
    10's lantern hangs in the ceiling hole at x 83, not in the rock at x 131.

The shape of the level, room by room:

    rooms 0-9   BLUE, magma in every corridor; a hole in every floor.
    room 6      an eight-cell magma block at cells 14-21 in open air, two
                holes either side of it; a snake in the right one.
    room 9      the breathing mouth over the one way down.
    room 10     ROCK; water from here to the end, and the level descends LEFT
                from here on, every right edge leading back up.
    rooms 11, 13  magma again: a two-cell pillar at 17-18 (a stick) in 11, a
                sixteen-cell wall at 10-25 over the water in 13, crossed on
                the RAFT (HL.RAFTS), which waits at its RIGHT end (x 124)
                because the hero comes in from the right.
    room 12     rock, two snakes; a two-cell pillar at 15-16 (a stick).
    room 14     an open corridor from edge to edge, solid floor.
    room 15     the miner's room, the miner at x 25.
"""
