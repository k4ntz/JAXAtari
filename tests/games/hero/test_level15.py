def test_the_engine_draws_the_bats_on_the_rom_clock(env):
    """The engine's creature positions over 184 frames sweep 22 px and repeat
    every 92 frames, and the bob repeats every 32 - room 1's bat."""
    import jax.numpy as jnp
    from jaxatari.games.jax_hero import _creature_pos
    c = env.consts
    slot = HL.SPIDERS[L - 1].index((1, 59, 64, 11, 1))
    xs, ys = [], []
    for t in range(0, 184):
        x, y = _creature_pos(c, jnp.int32(L - 1), jnp.int32(t))
        xs.append(int(x[slot])); ys.append(int(y[slot]))
    assert max(xs) - min(xs) == 22 and max(ys) - min(ys) == 7
    assert xs[:92] == xs[92:184], "the sweep is a 92-frame cycle"
    assert ys[:32] == ys[32:64] == ys[64:96], "the bob is a 32-frame cycle"


