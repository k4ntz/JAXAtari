def test_the_mouth_cycle_is_the_roms():
    """The engine's clock gives exactly the measured widths, frame by frame,
    and the cycle is 64 frames long."""
    import jax.numpy as jnp
    from jaxatari.games.jax_hero import _mouth_closed
    c = JaxHero().consts
    got = ""
    for e in range(128):
        closed = int(_mouth_closed(c, jnp.int32(L - 1), jnp.int32(e))[0])
        got += str(8 - 2 * closed)
    assert got == ROM_OPEN * 2


def _corridor(frame):
    row = np.asarray(frame)[80]
    magma = {(167, 26, 26), (184, 50, 50)}
    return "".join("%" if tuple(int(v) for v in row[9 + 4 * i]) in magma
                   else ("#" if row[9 + 4 * i].sum() else ".") for i in range(38))


def test_the_engine_draws_the_mouth_in_magma(env):
    import jax
    import jax.numpy as jnp
    _obs, state = env.reset(jax.random.PRNGKey(0))
    state = state.replace(level=jnp.int32(L - 1), room=jnp.int32(9),
                          player_x=jnp.int32(30), player_y=jnp.int32(0),
                          spider_alive=env.consts.SPIDER_VALID[L - 1])
    for e in range(0, 64, 4):
        band = _corridor(env.render(state.replace(room_timer=jnp.int32(e))))
        gap = band[14:22]
        n = int(ROM_OPEN[e])
        closed = (8 - n) // 2
        assert gap == "%" * closed + "." * n + "%" * closed, f"e {e}: {gap}"
        assert band[:14] == "%" * 14 and band[22:] == "%" * 16
    shut = env.render(state.replace(room_timer=jnp.int32(16), mouth_open=jnp.bool_(True)))
    assert _corridor(shut)[14:22] == "." * 8


def _in_room_9(env, **kw):
    import jax
    import jax.numpy as jnp
    _obs, state = env.reset(jax.random.PRNGKey(0))
    fields = dict(level=jnp.int32(L - 1), room=jnp.int32(9),
                  room_timer=jnp.int32(0), has_moved=jnp.bool_(True),
                  banner_timer=jnp.int32(0),
                  spider_alive=env.consts.SPIDER_VALID[L - 1])
    fields.update(kw)
    return state.replace(**fields)


def test_the_mouth_burns_and_then_stays_open_for_the_visit(env):
    """A hero hovering in the middle of the gap dies on the frame it shuts on
    him (e 16), and the respawn finds it open."""
    import jax.numpy as jnp
    state = _in_room_9(env, player_x=jnp.int32(77), player_y=jnp.int32(70))
    lives = int(state.lives)
    for _ in range(40):
        state = state.replace(player_x=jnp.int32(77), player_y=jnp.int32(70),
                              player_vy=jnp.float32(0))
        _obs, state, *_ = env.step(state, 0)
        if int(state.lives) < lives:
            break
    assert int(state.lives) == lives - 1 and int(state.room_timer) == 16
    assert int(state.room) == 9 and bool(state.mouth_open)


def test_room_9_is_passed_by_waiting_in_the_shaft(env):
    """The hero comes in through the ceiling hole at cells 17-18, over the
    gap. Falling straight in puts him in the gap as it shuts; hovering in
    the shaft until it begins to open and then dropping takes him through
    the floor hole at 16-19 into room 10."""
    import jax.numpy as jnp
    assert BANDS[9]["A"][17:19] == ".."

    def attempt(hover_until):
        # he comes in slowly, the rotor in its hover band: the ROM hero
        # cannot brake a 2 px/frame fall before the mouth (his thrust needs
        # ~40 frames of UP), so a fast entry dies whatever he does next
        state = _in_room_9(env, player_x=jnp.int32(77), player_y=jnp.int32(2),
                           player_vy=jnp.float32(0.0),
                           thrust_timer=jnp.int32(env.consts.thrust_hover))
        lives = int(state.lives)
        for _ in range(200):
            waiting = int(state.room_timer) < hover_until
            # hover by tapping UP to hold the thrust in its hover band
            act = (2 if int(state.thrust_timer) < 24 else 0) if waiting else 5
            _obs, state, *_ = env.step(state, act)
            if int(state.lives) < lives:
                return "died"
            if int(state.room) == 10:
                return "through"
        return "stuck"

    assert attempt(0) == "died"
    # one whole 64-frame mouth cycle in the shaft, and the drop is timed
    # (measured on the engine: waits of 4-16, 60-80 and 124-128 frames get
    # through, the 64-frame period of the mouth; the rest die)
    assert attempt(64) == "through"


