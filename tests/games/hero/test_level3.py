def test_the_corridors_are_not_all_room_0s():
    """The correction, for this level. The superseded capture gave all six
    rooms room 0's corridor band; the ROM draws five different ones, and the
    pillars they carry are the whole shape of the level.

    Rooms 1 and 2 really do draw the same corridor - both are open from cell
    2 to cell 33 - so the ROM keeps one copy of it. Neither of them has an
    interior pillar, so nothing of theirs can be shared and SHARED_WALLS
    stays empty all the same.
    """
    corridors = [b["B"] for b in BANDS]
    assert len(set(corridors)) == 5
    assert corridors[1] == corridors[2] == "##................................####"
    assert corridors[0] == "##...........##...................####"
    assert len({c for r, c in enumerate(corridors) if r != 2}) == 5


def test_the_pillars_are_where_the_rom_puts_them_not_where_room_0_has_one():
    """Room 0's pillar is at cells 13-14; rooms 3 and 4 have their own at
    cells 17-18 and 21-22, and rooms 1, 2 and 5 have none."""
    want = {0: (13, 14), 3: (17, 18), 4: (21, 22)}
    for room, band in enumerate(BANDS):
        b = band["B"]
        runs, start = [], None
        for i, ch in enumerate(b + "."):
            if ch == "#" and start is None:
                start = i
            elif ch != "#" and start is not None:
                runs.append((start, i - 1))
                start = None
        # a run that reaches the side of the screen is the cave wall, not a
        # pillar, and it never breaks
        interior = [r for r in runs if r[0] > 0 and r[1] < 37]
        assert interior == ([want[room]] if room in want else []), \
            f"room {room}: interior pillars {interior}"


def test_room_0_is_the_only_room_that_must_be_blasted():
    """Its hole at x 72-87 is past the pillar at x 60-67, and the ceiling
    above the pillar is that same two-cell pillar, so it cannot be flown
    over. Every other room has a hole reachable without a stick."""
    a, b, c = (BANDS[0][k] for k in "ABC")
    hole = [i for i, ch in enumerate(c) if ch == "."]
    assert cells(hole[0], hole[-1]) == (72, 16)
    assert b[13] == b[14] == "#" and a[13] == a[14] == "#"
    assert a[12] == a[15] == ".", "an isolated ceiling pillar, so it goes too"
    assert all(ch == "." for ch in b[2:13]), "the spawn side is open"
    assert all(ch == "#" for ch in c[:13]), "and its floor is solid"


def test_rooms_3_and_4_have_a_hole_on_the_side_they_are_entered_from():
    """Neither pillar has to be blasted on the route the level is played on.

    Room 2 drops him at x 48-55 or x 104-111; room 3's pillar is at x 76-83
    with a hole at x 40-47 on its left and x 112-119 on its right, so either
    entry has its own way down. Room 4's single hole at x 72-87 is left of
    its pillar at x 92-99, which is where room 3's left hole puts him.
    """
    for room, pillar in ((3, (17, 18)), (4, (21, 22))):
        b, c = BANDS[room]["B"], BANDS[room]["C"]
        entries = [i for i, ch in enumerate(BANDS[room]["A"]) if ch == "."]
        holes = [i for i, ch in enumerate(c) if ch == "."]
        pairs = {(e < pillar[0]) for e in entries} & {(h < pillar[0])
                                                      for h in holes}
        assert pairs, f"room {room}: no hole on the side it is entered from"
        assert all(ch == "#" for ch in b[pillar[0]:pillar[1] + 1])
        assert b[pillar[0] - 1] == b[pillar[1] + 1] == "."


