"""Level 3, against the corrected ROM reference.

The block in hero_levels.py is generated by tools/hero_gen/build_level.py,
which walks the level through the game's own room-transition code, captures
each room off the real ROM and refuses to emit anything unless the capture
agrees with the reference cell for cell. These tests re-check that agreement
from the committed data alone (no ale-py), then play the level.

Before the regeneration `level_images/tools/check_level.py 3` matched 1 of
the 6 rooms: the first capture pass kept ROOM 0's corridor band for every
room, so rooms 1-5 all carried room 0's pillar at x 60-67 and none of their
own. Room 3's real pillar is at x 76-83 and room 4's at x 92-99, and rooms
1, 2 and 5 have no interior pillar at all.

Level 3 is the first level with things levels 1 and 2 never had, and each of
them caught a bug in the generator or the engine:

  * two ceiling LANTERNS. A lantern's lamp is painted in exactly the miner's
    lamp-spark yellow, so classifying by that colour called both of them the
    miner and tripped "the miner is on the last screen".
  * three PATROLLING bats. SPIDERS holds the centre of a sweep, not its left
    end, and a sweep runs on its own clock: these bob on 64 frames and
    patrol on 184, where everything measured before held still sideways.

The route, room by room:

    room 0  spawn in the left corridor, blocked by the pillar at x 60-67
            whose ceiling is the same pillar, so it cannot be flown over
            -> plant a stick, run, +75, then down the hole at x 72-87
    room 1  open corridor and a 28-cell floor hole: nothing to do
    room 2  open corridor, holes at x 48-55 and x 104-111
    room 3  pillar at x 76-83 with a hole either side of it, so whichever
            side room 2 drops him on has its own way down
    room 4  pillar at x 92-99 and one hole at x 72-87, on the pillar's left
            - free from room 3's left hole, a blast from its right one
    room 5  the miner's room: solid floor, a bat, and the miner at x 25
"""
import numpy as np
