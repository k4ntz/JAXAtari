def test_the_flooded_floor_is_the_bottom_three_rows_of_room_5():
    """The last room is flooded exactly the way levels 1 and 2 are, over the
    wavy floor trim on rows 139-141. The floor band above it is solid rock,
    so it is a hazard and not a hole - there is no `~` cell in this level."""
    assert HL.DEADLY[2] == [(5, 8, 139, 152, 3)]
    assert "~" not in "".join(b[k] for b in BANDS for k in "ABC")
    ramp = {common.rgb(HL.SHADES[3][role]) for role in common.ROLES}
    img = HL.decode_bg(HL.BG_RLE_L3[5], HL.PALETTE_L3)
