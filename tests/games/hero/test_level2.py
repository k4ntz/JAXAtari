def test_room_2s_eleven_cell_slab_cannot_be_blasted_at_all():
    """Measured on the ROM: five sticks planted along room 2's corridor slab
    (x 64-107, eleven cells), every one confirmed to have gone off because the
    stock in RAM 50 dropped, and not one cell of it was ever removed - while a
    two-cell pillar broke on the first try in the same session. A run wider
    than two cells is immune, so it is not a blastable zone at all.

    The room is still passable: the floor hole at x 56-103 is reached from the
    LEFT corridor (cells 5-13, x 28-63), which overlaps it at cells 12-13.
    """
    assert [z for z in HL.DESTRUCTIBLE[1] if z[0] == 2] == []
    b, c = BANDS[2]["B"], BANDS[2]["C"]
    assert all(ch == "#" for ch in b[14:25]), "eleven solid corridor cells"
    first_gap = b.index(".")
    left_corridor = set(range(first_gap, b.index("#", first_gap)))
    hole = {i for i, ch in enumerate(c) if ch == "."}
    assert left_corridor & hole, "the way down is reachable without a blast"


def test_a_stick_takes_the_ceiling_only_when_the_ceiling_is_the_same_pillar():
    """The rule the old data got wrong, measured on the ROM twice over.

    Both of level 2's blastable walls are two-cell corridor pillars, but they
    do not blast the same way:

      room 0  ceiling A[13:15] is an ISOLATED two-cell pillar, air either
              side - one stick removes the ceiling AND the corridor, 83 px
      room 1  ceiling A[11:13] is part of a SIXTEEN-cell slab - one stick
              removes the corridor only, 39 px, and the ceiling stays

    Measured by planting sticks in the ROM and diffing the bands, and
    corroborated frame by frame against the recorded playthrough, which
    blasts both of these rooms: frames 13->14 for room 0 (ceiling band loses
    cells 13-14) and 28->29 for room 1 (ceiling band unchanged across frames
    29-35, with no unreadable cells in it).

    The floor band is never touched by a stick in either case.
    """
    zones = {z[0]: z for z in HL.DESTRUCTIBLE[1]}

    room0 = zones[0]
    assert room0 == (0, 60, 16, 8, 83, 1)
    assert BANDS[0]["A"][12] == BANDS[0]["A"][15] == ".",         "room 0's ceiling pillar has air either side of it"

    room1 = zones[1]
    assert room1 == (1, 52, 60, 8, 39, 1)
    assert room1[2] == 60 and room1[3] + room1[4] == 8 + 39,         "corridor band only: y 60, 39 px tall"
    assert all(ch == "#" for ch in BANDS[1]["A"][0:16]),         "room 1's ceiling there is a sixteen-cell slab, so it survives"

    # and neither of them ever reaches into the floor band
    for (_room, _x, y, _w, h, _ok) in HL.DESTRUCTIBLE[1]:
        assert y + h <= 99, "a stick never touches the floor band"


