"""Level 2, against the corrected ROM reference.

The block in hero_levels.py is generated by tools/hero_gen/build_level.py,
which walks the level through the game's own room-transition code, captures
each room off the real ROM and refuses to emit anything unless the capture
agrees with the reference cell for cell. These tests re-check that agreement
from the committed data alone (no ale-py), then play the level.

The bands below are the ROM's own, re-read after the game loaded each room
through its own transition code. The first capture pass kept room 0's
corridor band for every room of the level, which put room 1's pillar at
x 60-67 instead of x 52-59 and made rooms 0, 1 and 3 look like one wall
drawn three times; see level_images/CORRECTIONS.md, which uses this very
room as its worked example. Re-check them against the ROM with
`python tools/check_level.py 2` in level_images.

The route, as the beam search over this engine walks it:

    room 0  spawn at x 33 in the left corridor
            -> walk right, blocked by the pillar at x 60-67, whose ceiling is
               solid too, so it cannot be flown over
            -> plant a stick, run, +75
            -> walk right over the floor hole at x 72-87 and drop
    room 1  land at x ~76 in the right-hand corridor
            -> the floor hole at x 112-119 is on this side of the pillar at
               x 52-59, so nothing has to be blasted here
    room 2  land at x ~116, right of the 11-cell slab at x 64-107
            -> a stick opens the slab, then the wide hole at x 56-103
    room 3  the miner's room: no hole in the floor, a spider bobbing at
            x 108 and the miner at x 128
"""
