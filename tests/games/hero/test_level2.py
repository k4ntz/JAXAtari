def test_two_spiders_hang_still_and_two_bob_nine_pixels(env):
    """Measured off the ROM with the hero parked out of the picture, 400
    frames of each room: the two in rooms 2 and 3 that bob move over a 9 px
    span and come back over exactly 64 frames, and hold each of their two
    bitmaps for 8 frames. The other two never leave their row.

    SEVEN of those nine pixels are the creature moving and TWO are the art:
    the untethered spider's second pose is drawn two rows below its first, so
    the box it is ever inside is 17 rows tall for a sprite that is never more
    than 8. The engine carries the offset in the bitmap and the travel here,
    which is why this says 7 where the box says 9.

    Note this is NOT what CHARACTERS.md says for the bobbing pair - it
    reports 4.0 x 9.0 px at 70/72 frames over 17 sprites. That measurement
    tracks a frame-difference blob, whose box wanders as the body overlaps
    itself; measuring the sprite the ROM actually draws gives a box that is
    7 px wide in every frame and never moves sideways.
    """
    c = env.consts
    assert HL.CREATURE_MOTION[(2, 0)] == (0, 0, 8)
    assert HL.CREATURE_MOTION[(2, 1)] == (7, 32, 8)
    assert HL.CREATURE_MOTION[(2, 2)] == (0, 0, 8)
    assert HL.CREATURE_MOTION[(2, 3)] == (7, 32, 8)
    _, s = env.reset()
    s = s.replace(level=np.int32(1))      # reset() starts on level 1's roster
    seen = [(set(), set()) for _ in range(4)]
    for step in range(400):
        x, y = env._spider_pos(s.replace(step_counter=np.int32(step)))
        for i in range(4):
            seen[i][0].add(int(x[i]))
            seen[i][1].add(int(y[i]))
    assert seen[0] == ({60}, {70}), "room 1's spider hangs dead still"
    assert seen[2] == ({80}, {109}), "room 2's lower spider hangs dead still"
    for i in (1, 3):
        xs, ys = seen[i]
        assert len(xs) == 1, "it never moves sideways"
        assert (min(ys), max(ys)) == (65, 72), \
            "7 px of bob from its top row; the art carries the other two"
    assert int(c.SPIDER_BOB_HALF[1, 1]) == 32, "a 64-frame cycle"
    assert all(int(c.SPIDER_HOLD[1, i]) == 8 for i in range(4))


def test_the_magenta_surface_is_the_bottom_three_rows_of_room_3():
    """The last room is flooded exactly the way level 1's is, in magenta
    rather than blue, animated over the wavy floor trim on rows 139-141.
    The floor band above it is solid rock, so it is a hazard and not a
    hole - there is no `~` cell anywhere in this level.

    The rect is the union over the capture window, not one frame of it: the
    surface scrolls, so any given frame shows only part of the span it
    sweeps. It comes out the same rows and columns as level 1's water.
    """
    assert HL.DEADLY[1] == [(3, 8, 139, 152, 3)]
    liquid = np.array((168, 48, 143), np.uint8)
    img = HL.decode_bg(HL.BG_RLE_L2[3], HL.PALETTE_L2)
    wet = (img == liquid).all(-1)
    assert sorted(np.nonzero(wet.any(axis=1))[0].tolist()) == [139, 140, 141]
    # and no other room of the level has any of it
    for room in range(3):
        other = HL.decode_bg(HL.BG_RLE_L2[room], HL.PALETTE_L2)
        assert not (other == liquid).all(-1).any()


def test_room_0_is_green_and_not_level_1s_brown():
    """The fifth correction: the ROM only latches the cave palette on its
    first room transition, so a capture of room 0 comes back in level 1's
    brown. The generator maps the brown ramp onto the level's own, and this
    is what keeps room 0 the same green as the rest of the level."""
    shades = {common.rgb(HL.SHADES[2][role]) for role in common.ROLES}
    brown = {common.rgb(HL.SHADES[1][role]) for role in common.ROLES}
    room0 = HL.decode_bg(HL.BG_RLE_L2[0], HL.PALETTE_L2)
    painted = {tuple(int(v) for v in px) for px in room0.reshape(-1, 3)} - {(0, 0, 0)}
    assert painted <= shades, f"room 0 paints something off the green ramp: {painted - shades}"
    assert not painted & brown


# --- the walls --------------------------------------------------------------
# Where to start for each wall, which way to walk into it and which way to
# run afterwards. None of it is a free choice: walk at a wall across a floor
# hole and the hero drops through the hole instead, so each start has to be
# on the wall's own stretch of solid floor.
#
#   room 0  pillar x 60-67, floor solid from x 8 to 71 -> walk right from 16
#   room 1  pillar x 52-59, with holes at x 40-47 AND x 112-119 either side
#           of it, so the only approach is the solid strip x 48-111 between
#           them - which is exactly where room 0's hole drops him, x ~76
#
# Room 2's eleven-cell slab is absent because it is not blastable at all.
APPROACH = {
    (0, 60): (16, RIGHT, LEFT),
    (1, 52): (76, LEFT, RIGHT),
}


def _plant_against(env, room, x):
    """Walk up to the wall at `x`, plant a stick, run, and wait out the fuse."""
    c = env.consts
    from_x, towards, away = APPROACH[(room, x)]
    _, s = env.reset()
    s = s.replace(level=np.int32(1), room=np.int32(room),
                  spider_alive=np.zeros_like(s.spider_alive),
                  player_x=np.int32(from_x), player_y=np.int32(75))
    for _ in range(80):
        _, s, _, _, _ = env.step(s, towards)
    flush = x - c.player_width if towards == RIGHT else x + _wall_w(room, x)
    assert int(s.player_x) == flush,         f"room {room}: he should stop flush against the wall at x {x}"
    _, s, _, _, _ = env.step(s, DOWN)
    assert bool(s.dyn_active), f"room {room}: a stick goes down on solid ground"
    for _ in range(30):
        _, s, _, _, _ = env.step(s, away)
    for _ in range(c.dyn_fuse_playable + 6):
        _, s, _, _, _ = env.step(s, NOOP)
    return s


def _wall_w(room, x):
    return next(z[3] for z in HL.DESTRUCTIBLE[1] if z[0] == room and z[1] == x)


def test_each_of_the_two_walls_pays_its_own_seventy_five(env):
    """Two walls, two separate blasts, 75 each. Under the superseded data
    these were one shared wall that paid once."""
    c = env.consts
    assert len(HL.DESTRUCTIBLE[1]) == 2
    for slot, (room, x, *_rest) in enumerate(HL.DESTRUCTIBLE[1]):
        s = _plant_against(env, room, x)
        assert int(s.wall_stage[slot]) == 2, f"room {room}'s wall at x {x} must go"
        assert int(s.score) == c.wall_points == 75,             "one wall, one payment - none of them is shared"
        assert int(s.lives) == c.starting_lives, f"room {room}: fled in time"
        others = [i for i in range(len(HL.DESTRUCTIBLE[1])) if i != slot]
        assert all(int(s.wall_stage[i]) == 0 for i in others),             "blasting one of them must not clear the others"


def test_room_0s_pillar_blocks_the_way_down_until_it_is_blasted(env):
    _, s = env.reset()
    s = s.replace(level=np.int32(1), room=np.int32(0))
    for _ in range(120):                              # keep pushing right
        _, s, _, _, _ = env.step(s, RIGHT)
    assert int(s.room) == 0, "no way past the pillar without dynamite"
    assert int(s.player_x) == 54

    s = _plant_against(env, 0, 60)
    for _ in range(60):
        _, s, _, _, _ = env.step(s, RIGHT)
        if int(s.player_x) >= 76:
            break
    for _ in range(90):
        _, s, _, _, _ = env.step(s, NOOP)
        if int(s.room) == 1:
            break
    assert int(s.room) == 1, "the floor hole at x 72-87 leads to room 1"
