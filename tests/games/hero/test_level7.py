def test_room_0_is_blue_and_not_the_boot_palette_brown(env):
    """The ROM latches the cave palette on the first room transition, so a
    level booted by holding the level register down draws room 0 in level 1's
    BROWN. The capture maps the brown ramp back onto the level's own, and the
    old level-7 block is where that was visible: its palette carried the whole
    brown ramp beside the blue one."""
    import jax.numpy as jnp
    from jaxatari.games.jax_hero import HeroRenderer
    renderer = HeroRenderer(env.consts)
    _, s = env.reset()
    s = s.replace(level=jnp.int32(L - 1), room=jnp.int32(0))
    frame = np.asarray(renderer.render(s))[:142, :, :3]
    for role in ("dark", "mid", "light"):
        want = common.rgb(HL.SHADES[L][role])
        assert (frame == np.array(want)).all(axis=-1).any(), \
            f"room 0 does not paint its own {role} shade {HL.SHADES[L][role]}"
    brown = common.rgb(HL.SHADES[1]["mid"])
    assert not (frame == np.array(brown)).all(axis=-1).any(), \
        "and it paints none of level 1's brown"
