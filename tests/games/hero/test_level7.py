def test_the_water_of_room_10_is_lethal_and_still_not_a_way_down(env):
    """Both halves of the rule at once: he cannot fall through it, and he
    cannot stand on it either."""
    import jax.numpy as jnp
    c = env.consts
    _, state = env.reset()
    state = state.replace(level=jnp.int32(L - 1), room=jnp.int32(10),
                          player_x=jnp.int32(70), player_y=jnp.int32(62),
                          spider_alive=jnp.zeros_like(state.spider_alive))
    lives = int(state.lives)
    for _ in range(120):
        _obs, state, _r, _d, _i = env.step(state, jnp.int32(NOOP))
        if int(state.lives) != lives:
            break
    assert int(state.lives) == lives - 1, "the liquid surface kills him"
    assert int(state.room) == 10, "and it is not a way down"


