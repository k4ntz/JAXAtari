def test_flying_off_room_10s_right_edge_enters_room_11(env):
    """The engine has to do what the ROM does. He leaves by the right edge and
    arrives in room 11 near its left, keeping his height."""
    import jax.numpy as jnp
    c = env.consts
    _, state = env.reset()
    state = state.replace(level=jnp.int32(L - 1), room=jnp.int32(10),
                          player_x=jnp.int32(c.screen_width - 8
                                             - c.player_width),
                          player_y=jnp.int32(70),
                          spider_alive=jnp.zeros_like(state.spider_alive))
    y_before = int(state.player_y)
    for _ in range(12):
        _obs, state, _r, _d, _i = env.step(state, jnp.int32(RIGHT))
        if int(state.room) != 10:
            break
    assert int(state.room) == 11, "the right edge leads DOWN to room 11"
    assert int(state.player_x) == c.side_enter_right_x
    assert abs(int(state.player_y) - y_before) <= 2, "he keeps his height"


