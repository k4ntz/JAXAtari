def test_touching_the_tentacle_does_not_kill(env):
    """Measured on the ROM 2026-09-26: drawn over the hovering hero's legs and
    suit for 330 of 400 frames at four heights, it never took a life (the bat
    and the liquid did, in the same set-up). Here his box overlaps its
    tallest pose and he keeps his life; what kills over the water is the
    liquid."""
    import jax.numpy as jnp
    from jaxatari.games.jax_hero import _tentacle_box
    slot = _tentacle_slot()
    c = env.consts
    y = 131 - c.player_height + 1                     # feet on row 131
    top, h = (int(v) for v in _tentacle_box(jnp.int32(32)))
    assert top <= 131 < top + h, "the boxes do overlap at pose 4"
    s = _state(env, TENTACLE_ROOM, player_x=jnp.int32(77), player_y=jnp.int32(y),
               room_timer=jnp.int32(31),
               tentacle_x=jnp.zeros_like(c.SPIDER_VALID[L - 1],
                                         dtype=jnp.int32).at[slot].set(77))
    s = s.replace(spider_alive=s.spider_alive & (jnp.arange(c.num_spiders) == slot))
    lives = int(s.lives)
    for _ in range(3):
        s = s.replace(player_y=jnp.int32(y), player_vy=jnp.float32(0))
        _obs, s, *_ = env.step(s, 0)
        assert int(s.lives) == lives
    assert bool(s.spider_alive[slot])


