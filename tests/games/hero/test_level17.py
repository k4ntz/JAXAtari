def test_the_tentacle_follows_him_a_pixel_every_4_frames(env):
    """Measured with the hero held at x 157, then 17, then 91: it swims to the
    right clamp 121, back to the left clamp 29, then settles under him at
    91, a pixel every 4 frames on room_timer % 4 == 1."""
    import jax.numpy as jnp
    from jaxatari.games.jax_hero import _tentacle_follow
    c = env.consts
    slot = _tentacle_slot()
    lvl = jnp.int32(L - 1)
    tx = jnp.zeros((c.num_spiders,), jnp.int32).at[slot].set(121)
    trace = [121]                                      # trace[e]: x after frame e
    for e in range(1, 500):
        tx = _tentacle_follow(c, lvl, tx, jnp.int32(91), jnp.int32(e),
                              jnp.bool_(False))
        trace.append(int(tx[slot]))
    assert trace[-1] == 91 and min(trace) == 91
    moves = [e for e in range(1, len(trace)) if trace[e] != trace[e - 1]]
    assert all(e % 4 == 1 for e in moves), "on room_timer % 4 == 1 only"
    assert len(moves) == 121 - 91
    for hero, want in ((157, 121), (17, 29)):
        t = jnp.zeros((c.num_spiders,), jnp.int32).at[slot].set(91)
        for e in range(1, 500):
            t = _tentacle_follow(c, lvl, t, jnp.int32(hero), jnp.int32(e),
                                 jnp.bool_(False))
        assert int(t[slot]) == want


