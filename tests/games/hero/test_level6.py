"""Level 6, against the corrected ROM reference.

The block in hero_levels.py is generated by tools/hero_gen/build_level.py,
which walks the level through the game's own room-transition code, captures
each room off the real ROM and refuses to emit anything unless the capture
agrees with the reference cell for cell. These tests re-check that agreement
from the committed data alone (no ale-py), then play the level.

Level 6 is the last of the levels CORRECTIONS.md calls complete, and the
first one whose CREATURES are not all animated on one clock. The geometry
came straight out of the walk - ten rooms, no room refused, no `?` cell, and
`hero_extract.py verify 6` reports 0 band mismatches - so the interesting
work was all in the cast:

  * THE BOBBING SPIDERS BOB ON 72 FRAMES, NOT 64. 64 is the BAT's vertical
    cycle. The capture votes over a short window and quantises the one onto
    the other; the census watches 420 frames and autocorrelates, and it puts
    the spider at 70/72 against the bat's 184/64 - which is what CHARACTERS.md
    and CORRECTIONS.md both say. Rooms 1, 5 and 7 have one each.
  * SIX OF THE ELEVEN CREATURES ARE STILL. "Whether a creature moves is a
    property of the room, not of the creature" (CHARACTERS.md): the census
    sees these six draw a single sprite for the whole scan, so they are drawn
    as a single sprite. Before CREATURE_SPRITES the pose clock ran for them
    too and a spider the ROM never redraws swapped its legs every 8 frames.
  * THE POSE HOLD IS STILL THE CAPTURE'S, deliberately. The census reports 1
    frame per sprite for every bobbing spider, and that is the artefact that
    made level 4's snakes "14 poses of 1 frame each" - the component pass
    splits the 1 px thread off the body and rejoins it, so the mask changes
    every frame while the ROM has redrawn nothing.

Magma is in the five EVEN rooms, and in each of them every solid corridor
cell is magma, because the corridor colour register is either the level hue
or magma red and nothing in between.

The route, room by room:

    room 0  magma corridor, blocked by the pillar at x 60-67 whose ceiling is
            the same pillar -> plant a stick, run, +75, then down the hole at
            x 72-87
    room 1  a lantern, a bobbing spider at x 96 and a bat patrolling the FLOOR
            band; a pillar at x 60-67 and holes at x 20-55 and x 104-139
    room 2  magma; the pillar at x 92-99 and the hole at x 72-87
    room 3  the widest corridor of the level, a patrolling bat at x 32-60 and
            a still spider on the floor; four two-cell holes
    room 4  magma down both sides and a magma pillar at x 76, holes at
            x 52-59 and x 100-107
    room 5  an eleven-cell slab in mid-corridor - too wide to blast, so it is
            flown around; a bobbing spider at x 112, a still one at x 60, and
            one wide hole from x 40 to x 115
    room 6  magma at the edges only, a still spider at x 24, holes at x 24-31
            and x 128-135
    room 7  a bobbing spider at x 64, a still one at x 104, the pillar at
            x 76-83 and holes at x 48-55 and x 104-111
    room 8  magma, the pillar at x 60-67, the hole at x 72-87
    room 9  the miner's room: sealed floor, a flooded trim, a still spider at
            x 53 and the miner at x 25
"""
