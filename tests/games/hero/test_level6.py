def test_every_entity_in_characters_md_is_present():
    """The level's whole cast, room by room, against CHARACTERS.md.

    Lanterns, spiders and the miner are compared exactly. A BAT is compared
    against its patrol envelope instead of the centre the table prints - see
    the note on CHARACTERS_MD above - and the tolerance is the 2 px the tight
    box trims off the spread wing, never more.
    """
    got = [(r, "lantern", x, y) for r, x, y in HL.LANTERNS[L - 1]]
    got.append(("miner",) and (HL.MINER_POS[L - 1][0], "miner",
                               HL.MINER_POS[L - 1][1], HL.MINER_POS[L - 1][2]))
    # CHARACTERS.md calls both of the ROM's spiders a "Spider" in this level,
    # and it is right to: kind 0 is the one that hangs under a thread and
    # kind 4 the one that floats without one, and they are the same animal as
    # far as the table is concerned. (In level 7 the census loses track of
    # that and calls a still kind 4 a "Bat", which is what made this
    # distinction worth measuring - see test_level7.)
    kinds = {0: "spider", 1: "bat", 4: "spider"}
    for room, x, y, patrol, kind in HL.SPIDERS[L - 1]:
        got.append((room, kinds[kind], x - patrol, y))

    assert len(got) == len(CHARACTERS_MD) == 20
    for room, what, x, y in CHARACTERS_MD:
        near = [g for g in got
                if g[0] == room and g[1] == what
                and abs(g[2] - x) <= 2 and abs(g[3] - y) <= 1]
        assert near, f"CHARACTERS.md row ({room}, {what}, {x}, {y}) is missing"
        if what != "bat":
            assert (room, what, x, y) in got, \
                f"({room}, {what}) must match CHARACTERS.md exactly"


