def test_the_direction_of_every_side_exit_is_recorded_not_derived():
    """A side exit's direction is DATA. Level 5 descends through a LEFT edge,
    level 7 through a RIGHT one, and level 8 through LEFT edges again - while
    room 11's and room 12's RIGHT edges lead back UP. Taking the right edge
    of room 11 as 'an exit' is what stopped the walk three rooms early."""
    by_room = {}
    for room, side, delta in HL.SIDE_EXITS[L - 1]:
        by_room.setdefault(room, {})[side] = delta
    assert by_room[10] == {-1: 1}
    assert by_room[11] == {-1: 1, 1: -1}
    assert by_room[12] == {-1: 1, 1: -1}
    assert by_room[13] == {1: -1}, "the last room leads nowhere but back"


