def test_a_liquid_cell_is_solid_only_on_the_rows_it_is_drawn_on():
    """'~' is air from row 99 to 135 and filled on 136-141, so its wall rect
    is those six rows and not the whole 43 px band. A rect over the whole
    band is an invisible ledge the hero stands on 37 px above the water."""
    y0, y1 = common.LIQUID_ROWS
    for room in (10, 11, 12):
        liquid_x = {8 + 4 * i for i, c in enumerate(BANDS[room]["C"]) if c == "~"}
        for x, y, w, h in HL.WALL_RECTS_L8[room]:
            if x in liquid_x and y >= 99:
                assert (y, h) == (y0, y1 - y0 + 1), (
                    f"room {room}: the liquid rect at x {x} is {h} px tall "
                    f"from row {y}; it must be rows {y0}-{y1}")


def test_the_deadly_rects_are_the_water_line():
    """DEADLY is the lethal surface, taken from the pixels the ROM draws off
    the level's rock ramp. Level 8's water is GREEN (#328432) in a grey cave,
    which is what makes it findable at all.

    Room 13 carries a three-row strip although its floor is solid rock. That
    is what the ROM draws - the same green along rows 139-141 - and it sits
    UNDER 40 px of rock, so nothing can reach it. It is recorded because it
    is drawn, not because it was measured to kill."""
    rooms = {r for r, _x, _y, _w, _h in HL.DEADLY[L - 1]}
    assert rooms == {10, 11, 12, 13}
    for room, x, y, w, h in HL.DEADLY[L - 1]:
        assert y + h - 1 <= 141, "the surface cannot reach past the floor band"
        if room != 13:
            assert (y, h) == (136, 6), f"room {room} water is not the 136-141 line"
    assert (13, 8, 139, 152, 3) in HL.DEADLY[L - 1]


