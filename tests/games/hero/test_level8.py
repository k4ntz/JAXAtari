def test_room_0_is_grey_and_not_the_boot_palette_brown():
    """The ROM leaves level 1's brown palette in place until the first room
    transition, so room 0 came back brown and is recoloured onto the level's
    own ramp. Level 8's ramp is grey, and a grey ramp has r == g == b."""
    _palette, rooms = common.level_data(L)
    room0 = rooms[0]
    for role in ("dark", "mid", "light"):
        r, g, b = common.rgb(HL.SHADES[L][role])
        assert r == g == b, f"{role} is not a grey"
        assert (room0 == np.array([r, g, b])).all(axis=-1).any(), (
            f"room 0 never paints its {role}")
