"""Level 8, against the corrected ROM reference.

The block in hero_levels.py is generated by a level builder that walks
the level through the game's own room-transition code, captures
each room off the real ROM and refuses to emit anything unless the capture
agrees with the reference cell for cell. These tests re-check that agreement
from the committed data alone (no ale-py), then play the level.

Level 8 is the first level that needed DYNAMITE to be captured at all, and
three things came out of it:

  * THE WALK NOW REACHES ALL FOURTEEN ROOMS. The old reference had it at 11.
    Room 10 is left through its open LEFT edge, but only from near that edge:
    dropped mid-corridor the hero is over the water and drowns, and holding
    the rotor flies him out of the TOP of the screen and back up to room 9.
  * A ROOM CAN OPEN ON BOTH SIDES, AND ONE SIDE LEADS BACK UP. Room 11's
    cell 37 returns to room 10. The walker used to accept that as "an exit"
    and stop, three rooms short, so a way out now only counts if it lands
    further DOWN the chain.
  * ROOM 11 IS SEALED BEHIND A PILLAR. Its corridor is open at cell 0, but
    cells 2-3 are a two-cell pillar under a ceiling that is solid across the
    whole room, so the hero can neither walk past it nor fly over it. Every
    action from every drop point failed to leave in 1500 frames. A stick
    takes it - stock 6 -> 5 - and LEFT then reaches room 12 in 17 frames.
    Rooms 12 and 13 exist only on the far side of that blast.

The shape of the level, room by room:

    rooms 0-10  GREY, and magma in every one of them - level 8 is the first
                level whose corridor register is magma red all the way down.
    room 10     the water room: the corridor is open end to end but for two
                magma cells at the right, and the floor is liquid from cell 8
                to cell 27. The way on is the open LEFT edge.
    room 11     sealed ceiling, liquid floor, a patrolling BAT over the water
                and a SNAKE out of the middle slab's right face. Blast the
                cells 2-3 pillar to leave.
    room 12     liquid floor in two stretches, a hanging spider and a second
                snake. Its left edge leads on, and needs no stick.
    room 13     the miner's room: solid floor, solid ceiling, one hanging
                creature and the miner at x 25.

Rooms 0 and 10-13 have NO row in the census - it was taken when
the walker still stopped at room 10 - so their entities come from the capture
and are checked against it, not against a table that never saw them.
"""
