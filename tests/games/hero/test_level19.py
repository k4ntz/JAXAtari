"""Level 19, against the corrected ROM reference.

The block in hero_levels.py is generated by tools/hero_gen/build_level.py,
which walks the level through the game's own room-transition code, captures
each room off the real ROM and refuses to emit anything unless the capture
agrees with the reference cell for cell. These tests re-check that agreement
from the committed data alone (no ale-py), and check the engine draws it.

What came out of level 19:

  * THE WALK REACHES ALL SIXTEEN ROOMS. The reference had eleven (all read
    off the ROM, all confirmed); rooms 11-15 were appended from the walk.
    The capture used to stop at room 14: its way on is a two-cell magma
    pillar at the LEFT edge (cells 2-3) that has to be blown, and the room's
    on-screen watch left the hero hard against it. rom_capture now retries
    the exits from the state the room was entered in.
  * THE OLD BLOCK WAS A PLACEHOLDER copy of level 15. Every table is new
    (tools/hero_gen/split_placeholder.py gave the level its own slots first).
  * ITS CREATURES RUN AT LEVEL 18'S SPEED: nine bats sweep 22 px on 46 frames
    and bob 7 px on 16; the seven untethered spiders bob 7 px on 16, their
    pose locked to the direction. The eight hanging spiders are still.
  * TWO WALL SNAKES, both in the CORRIDOR (rooms 8 and 10), stretch a pixel
    every frame: the 16-frame cycle level 18's floor snakes run.
  * TWO WATER TENTACLES (kind 5), rooms 11 and 14, each pursuing between
    x 29 and 121 over the liquid at x 28-131.
  * ROOM 6 BREATHES MAGMA (HL.MAGMA_MOUTHS), the eight air cells 14-21.
  * ONE RAFT (HL.RAFTS), room 12, at the RIGHT end (x 124): the level
    descends LEFT, so the hero comes in from the right.
  * THE LIQUID IS BROWN, #a26221, not the #2d32b8 hero_rooms.json gives -
    the same as levels 11 and 15. The AtariAge map draws it brown too.
  * TWO 2-ROW "CREATURES" IN ROCK COLOURS were the picture drawn two rows
    low from the above-picture park (rooms 12 and 15): the ceiling's last two
    rows on rows 60-61 of the open corridor. rom_capture drops them.
  * CHARACTERS.md's census had 16 entities in 10 rooms; the capture has 39
    (28 creatures, 10 lanterns, the miner) and the AtariAge map of the level
    agrees in every room. The census's room 10 "bat" at (52, 111) is not on
    the ROM: its room 9's floor spider sits at x 52.

The shape of the level, room by room:

    rooms 0-9   BLUE; magma in every corridor but room 7's, which is rock.
    room 6      the breathing mouth over the way down.
    room 10     water under the whole floor; left through its open LEFT edge.
    rooms 11-15 water from here to the end; the level descends LEFT, every
                right edge leading back up.
    rooms 11,14 the tentacles.
    room 12     a sixteen-cell magma wall over the water, crossed on the raft.
    room 15     the miner's room, the miner at x 25.
"""
