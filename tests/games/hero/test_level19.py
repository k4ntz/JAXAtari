def test_he_can_fly_off_the_raft_and_hover_under_the_magma(env):
    import jax.numpy as jnp
    c = env.consts
    s = _state(env, 12, raft_x=jnp.int32(80), raft_dir=jnp.int32(-1),
               player_x=jnp.int32(81), player_y=jnp.int32(c.raft_y - c.player_height),
               spider_alive=jnp.zeros_like(c.SPIDER_VALID[L - 1]))
    lives = int(s.lives)
    ys = []
