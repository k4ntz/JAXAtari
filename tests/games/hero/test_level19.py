def test_a_death_on_the_raft_leaves_it_and_brings_him_back_onto_it(env):
    """Carried from x 124 leftwards into room 12's floor spider, he dies; the
    raft waits where it stopped, he comes back in his own column under the
    magma wall, lands on it and it carries him on to the left. (100 frames:
    by 150 it has reached x 28, turned and carried him back into the spider.)"""
    import jax.numpy as jnp
    c = env.consts
    s = _state(env, 12, raft_x=jnp.int32(124), raft_dir=jnp.int32(-1),
               player_x=jnp.int32(125), player_y=jnp.int32(c.raft_y - c.player_height))
    lives = int(s.lives)
    died_at = None
    for f in range(100):
        prev = s
        _obs, s, *_ = env.step(s, 0)
        if died_at is None and int(s.lives) < lives:
            died_at = f
            assert int(s.player_y) == c.respawn_low_y, "under the magma wall"
            assert abs(int(s.player_x) - int(prev.player_x)) <= 1, "in his own column"
            raft_at_death = int(s.raft_x)
        elif died_at is not None and int(s.player_y) < c.raft_y - c.player_height:
            assert int(s.raft_x) == raft_at_death, "the raft waits where it stopped"
    assert died_at is not None
    assert int(s.player_y) == c.raft_y - c.player_height, "back on the raft"
    assert int(s.raft_x) < raft_at_death, "and it carries him on"


@pytest.mark.parametrize("room, x, y, low", [(5, 76, 72, False), (12, 76, 104, True),
                                             (2, 119, 64, False), (2, 71, 104, True)])
def test_he_comes_back_at_the_height_of_the_band_he_died_in(env, room, x, y, low):
    """Pinned where a creature kills him, the hero comes back in his own
    column at corridor height (y 62) when the creature is in the corridor
    band and at y 101 when it is in the floor band."""
    import jax.numpy as jnp
    c = env.consts
    s = _state(env, room, player_x=jnp.int32(x), player_y=jnp.int32(y),
               room_timer=jnp.int32(0), step_counter=jnp.int32(0))
    lives = int(s.lives)
