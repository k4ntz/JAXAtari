def test_the_liquid_is_brown_not_the_json_blue():
    """hero_rooms.json says #2d32b8; the ROM paints (162, 98, 33) on the water
    rows of rooms 10-15 and nowhere else, as on levels 11 and 15."""
    palette, rooms = common.level_data(L)
    assert common.rgb(LIQUID) in palette
    assert common.rgb("#2d32b8") not in palette
    for i, img in enumerate(rooms):
        ys, _xs = np.nonzero((img == np.array(common.rgb(LIQUID))).all(axis=-1))
        if i >= 10:
            assert ys.size and ys.min() >= 136, f"room {i}"
        else:
            assert not ys.size, f"room {i} paints the liquid colour"


