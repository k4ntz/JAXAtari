def test_room_1_has_one_spider_that_never_moves():
    """Measured over 1800 frames with the hero parked off screen: the thread
    hangs from y 70 and the body never leaves it. It only swaps between two
    poses a pixel apart, about every 8 frames. Giving it the spider
    archetype's +-5 px bob would be wrong for this level."""
    assert HL.LANTERNS[0] == [], "level 1 has no lamp (that one is the miner's)"
