def test_room_1_corridor_is_open_end_to_end():
    """The correction that made this level wrong for so long.

    The first capture gave room 1 room 0's corridor, pillar and all. The ROM
    draws rock only where the corridor meets the two side walls; everything
    between x 24 and x 135 is air, so the hero walks from the drop straight
    to the miner.
    """
    b = BANDS[1]["B"]
    assert b == "####............................######"
    assert b[13] == b[14] == ".", "no pillar at x 60-67 in room 1"
    img = HL.decode_bg(HL.BG_RLE_L1[1], HL.PALETTE_L1)
    assert common.bands_of(img)["B"] == b
    # and nothing claims to be solid there, in the rects or in the blastables
    assert not [r for r in HL.WALL_RECTS_L1[1] if r[0] == 60]
    assert [z for z in HL.DESTRUCTIBLE[0] if z[0] == 1] == []
    assert HL.SHARED_WALLS[0] == [], "one pillar, on one screen, is not shared"


