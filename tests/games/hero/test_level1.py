def test_the_spider_is_drawn_and_hit_at_the_same_still_spot(env):
    c = env.consts
    _, s = env.reset()
    s = s.replace(room=np.int32(1))
    xs, ys = set(), set()
    for step in range(200):
        x, y = env._spider_pos(s.replace(step_counter=np.int32(step)))
        xs.add(int(x[0]))
        ys.add(int(y[0]))
    assert xs == {49} and ys == {70}, "it hangs still, whatever the frame"
    assert int(c.SPIDER_BOB[0, 0]) == 0
    assert int(c.SPIDER_HOLD[0, 0]) == 8


def test_the_water_strip_is_the_bottom_three_rows_of_room_1():
    """The ROM floods the last room and animates the surface over the wavy
    floor trim; the capture keeps the phase the ROM holds for four frames in
    every five. Water reaches rows 139-141 and nothing above them."""
    assert HL.DEADLY[0] == [(1, 8, 139, 152, 3)]
    water = np.array((45, 50, 184), np.uint8)
    img = HL.decode_bg(HL.BG_RLE_L1[1], HL.PALETTE_L1)
    wet = (img == water).all(-1)
    assert sorted(np.nonzero(wet.any(axis=1))[0].tolist()) == [139, 140, 141]
    assert wet[141, 8:160].mean() > wet[140, 8:160].mean() > wet[139, 8:160].mean()
    # and room 0, which is not flooded, has none of it
    assert not (HL.decode_bg(HL.BG_RLE_L1[0], HL.PALETTE_L1) == water).all(-1).any()


# --- the pillar -------------------------------------------------------------
def _plant_against_the_pillar(env):
    c = env.consts
    _, s = env.reset()
    for _ in range(40):                               # walk right until blocked
        _, s, _, _, _ = env.step(s, RIGHT)
    assert int(s.player_x) == 54, "he should stop flush against the pillar"
    _, s, _, _, _ = env.step(s, DOWN)
    assert bool(s.dyn_active)
    for _ in range(30):
        _, s, _, _, _ = env.step(s, LEFT)
    for _ in range(c.dyn_fuse_playable + 6):
        _, s, _, _, _ = env.step(s, NOOP)
    return s


def test_one_blast_opens_the_only_wall_in_the_level(env):
    """Level 1 has exactly one blastable wall - room 0's pillar - so a clean
    clear scores 75 for rock, once."""
    s = _plant_against_the_pillar(env)
    assert len(HL.DESTRUCTIBLE[0]) == 1
    assert int(s.wall_stage[0]) == 2, "room 0's pillar must go"
    assert int(s.score) == env.consts.wall_points == 75
    assert int(s.lives) == env.consts.starting_lives


def test_the_pillar_blocks_the_way_down_until_it_is_blasted(env):
    _, s = env.reset()
    for _ in range(120):                              # keep pushing right
        _, s, _, _, _ = env.step(s, RIGHT)
    assert int(s.room) == 0, "no way past the pillar without dynamite"
    assert int(s.player_x) == 54

    s = _plant_against_the_pillar(env)
    for _ in range(60):
        _, s, _, _, _ = env.step(s, RIGHT)
        if int(s.player_x) >= 76:
            break
    for _ in range(90):
        _, s, _, _, _ = env.step(s, NOOP)
        if int(s.room) == 1:
            break
    assert int(s.room) == 1, "the floor hole at x 72-87 leads to room 1"


# --- the whole level --------------------------------------------------------
def test_the_rom_route_clears_level_1(env):
    """Walk the route the ROM's own bot walks and finish the level."""
    c = env.consts
    _, s = env.reset()
    total = 0.0

    def go(action, n, until=None):
        nonlocal s, total
        for _ in range(n):
            _, s, r, _, _ = env.step(s, action)
            total += float(r)
            if until and until(s):
                break

    go(RIGHT, 40)                                     # up against the pillar
    go(DOWN, 1)                                       # plant
    go(LEFT, 30)                                      # and run
    go(NOOP, c.dyn_fuse_playable + 6)
    assert int(s.score) == 75

    go(RIGHT, 60, until=lambda t: int(t.player_x) >= 76)
    go(NOOP, 90, until=lambda t: int(t.room) == 1)
    assert int(s.room) == 1
    go(NOOP, 120, until=lambda t: int(t.player_y) >= 75)   # the drop is ~78 px
    assert int(s.player_y) == 75, "he should be standing on room 1's floor"

    # the spider hangs between him and the miner. Touching it costs a life
    # whether or not the button is down, so it has to be shot from a
    # distance first - which is what the ROM's own run does, killing it at
    # f7 from 20 px away.
    go(LEFT, 20, until=lambda t: int(t.player_x) <= 72)
    go(FIRE, 60, until=lambda t: not bool(t.spider_alive[0]))
    assert not bool(s.spider_alive[0]), "the bolt must clear the way"
    go(LEFT, 80, until=lambda t: int(t.player_x) <= 26)
    assert int(s.level) == 1, "rescued and moved on to level 2"
    assert int(s.lives) == c.starting_lives, "cleared without dying"
    # 75 wall + 1000 miner + the power tally; HERO_SPEC measured a clean
    # level-1 clear at 2,400-2,700 including any creature killed on the way
    assert 2400 <= total <= 2700, total
