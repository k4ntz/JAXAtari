"""Level 1, against the corrected ROM reference.

The block in hero_levels.py is generated by walking the level through the
game's own room-transition code, capturing each room off the real ROM and
refusing to emit anything unless the capture agrees with the reference cell
for cell. These tests re-check that agreement from the committed data alone
(no ale-py), then play the level.

The bands below are the ROM's own, re-read after the game loaded each room
through its own transition code. The first capture pass kept room 0's
corridor band for room 1 as well, which put a pillar at x 60-67 in room 1
that the ROM does not draw.

The route:

    room 0  spawn at x 33 in the left corridor
            -> walk right, blocked by the pillar at x 60-67
            -> plant a stick, run, +75
            -> walk right over the floor hole at x 72-87 and drop
    room 1  land at x ~76 in a corridor that is open end to end
            -> walk left, shooting the spider that hangs at x 49
            -> touch the miner at x 25, +1000 and the level ends
"""
