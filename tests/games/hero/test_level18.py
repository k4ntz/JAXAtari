def test_dynamite_beside_it_takes_the_pillar_and_not_the_tentacle(env):
    """Room 11's rock pillar at cells 32-33 (x 136-143), a stick planted on
    the floor right of it with the tentacle waiting at its right clamp."""
    import jax.numpy as jnp
    slot = _tentacle_slot()
    c = env.consts
    assert runs_of(BANDS[TENTACLE_ROOM]["B"], "#")[-1] == (32, 33)
    s = _state(env, TENTACLE_ROOM, player_x=jnp.int32(144),
               player_y=jnp.int32(99 - c.player_height), room_timer=jnp.int32(200),
               tentacle_x=jnp.zeros_like(c.SPIDER_VALID[L - 1],
                                         dtype=jnp.int32).at[slot].set(121))
    s = s.replace(spider_alive=s.spider_alive & (jnp.arange(c.num_spiders) == slot))
    score = int(s.score)
    _obs, s, *_ = env.step(s, 5)                      # DOWN: plant
    assert bool(s.dyn_active)
    for _ in range(120):
        _obs, s, *_ = env.step(s, 0)
    assert int(s.score) - score == c.wall_points, "the pillar, and nothing else"
    assert bool(s.spider_alive[slot]), "the tentacle survives the blast"


