def test_the_engine_locks_the_untethered_spiders_pose_to_its_bob(env):
    """The ROM's cycle, frame by frame (ROM_FREE): the positions and the pose
    order are the ROM's. The engine's triangle wave rounds its ends
    differently - it holds the top 3 frames and the bottom 1 where the ROM
    holds each 2 - so its upward half runs up to 1 px ahead: the same
    rounding every bobbing creature in the game gets from _creature_pos."""
    import jax.numpy as jnp
    from jaxatari.games.jax_hero import _creature_pos
    c = env.consts
    slot = HL.SPIDERS[L - 1].index((1, 24, 104, 0, 4))
    got = []
    for t in range(32):
        _x, y = _creature_pos(c, jnp.int32(L - 1), jnp.int32(t))
        pose = (t // int(c.SPIDER_HOLD[L - 1][slot])) % 2   # 1 = _ART2
        got.append((int(y[slot]), pose))
    # pose 1 (legs gathered) exactly while it goes down, as on the ROM
    down = [p for (y0, p), (y1, _q) in zip(got, got[1:]) if y1 > y0]
    up = [p for (y0, p), (y1, _q) in zip(got, got[1:]) if y1 < y0]
    assert set(down) == {1} and set(up) == {0}
    assert {y for y, _p in got} == {y for y, _p in ROM_FREE} == set(range(104, 112))
    assert got[:16] == got[16:], "a 16-frame cycle"


