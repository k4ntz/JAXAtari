def test_the_tentacle_starts_at_the_heros_entry_x_clamped(env):
    """The level descends RIGHT: in by room 10's open right edge he appears
    on the LEFT of room 11 and the tentacle at its left clamp, 29; back up by
    room 12's left edge he appears on the right and it waits at 121."""
    import jax.numpy as jnp
    slot = _tentacle_slot()
    c = env.consts
    none = jnp.zeros_like(c.SPIDER_VALID[L - 1])
    s = _state(env, 10, player_x=jnp.int32(c.screen_width - 8 - c.player_width),
               player_y=jnp.int32(70), spider_alive=none)
    _obs, s, *_ = env.step(s, 3)                       # RIGHT, off the edge
    assert int(s.room) == 11 and int(s.tentacle_x[slot]) == 29
    s = _state(env, 12, player_x=jnp.int32(8), player_y=jnp.int32(70),
               spider_alive=none)
    _obs, s, *_ = env.step(s, 4)                       # LEFT, off the edge
    assert int(s.room) == 11 and int(s.tentacle_x[slot]) == 121


