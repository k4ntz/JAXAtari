"""Level 20, against the corrected ROM reference.

The block in hero_levels.py was generated by walking the level through the
game's own room-transition code, capturing each room off the real ROM and
refusing to emit anything unless the capture agreed with the reference cell
for cell. These tests re-check that agreement from the committed data alone
(no ale-py), and check the engine draws it.

What came out of level 20, the last level of the game:

  * THE WALK REACHES ALL SIXTEEN ROOMS. The reference had eleven (all read
    off the ROM, all confirmed); rooms 11-15 were appended from the walk.
  * THE OLD BLOCK WAS A PLACEHOLDER copy of level 16, the last one. Every
    table is new, and hero_levels.py no longer has a placeholder at all.
  * ITS CREATURES RUN AT LEVEL 18'S SPEED: fourteen bats sweep 22 px on 46
    frames and bob 7 px on 16; the five untethered spiders bob 7 px on 16,
    their pose locked to the direction. The seven hanging spiders are still.
  * ONE WALL SNAKE, room 3, in the CORRIDOR, grows out of the magma wall on
    its left a pixel every frame (the 16-frame cycle).
  * TWO WATER TENTACLES (kind 5), rooms 12 and 14, each pursuing between
    x 29 and 121. Room 14's was watched with every pose drawn two rows low;
    the capture re-reads a tentacle with the hero parked in the corridor
    (the same five poses as room 12's and level 17's, measured).
  * ROOM 5 BREATHES MAGMA (HL.MAGMA_MOUTHS), the eight air cells 14-21.
  * ONE RAFT (HL.RAFTS), room 11, at the LEFT end (x 28): the level
    descends RIGHT, so the hero comes in from the left.
  * THE LIQUID IS GREEN, #328432, as the reference says.
  * NINE CREATURES WERE 1-2 ROWS LOW in the capture and were re-read with the
    hero in the room - three of them (rooms 3, 5, 9) from parks the tool had
    never used: an 8-px gap off the 4-px grid, a gap beside the creature, and
    the first 16 frames in room 5's mouth before it shuts.
  * The old census had 17 entities in 10 rooms; the capture has 39
    (29 creatures, 9 lanterns, the miner) and the AtariAge map of the level
    agrees in every room, lamp for lamp. The census's room 10 corridor
    "spider" at (56, 66) is inside the rock.

The shape of the level, room by room:

    rooms 0-9   GREY; magma in every corridor but room 2's, which is rock.
    room 5      the breathing mouth over the way down.
    room 9      the only one of rooms 1-10 with no lamp.
    room 10     water under the whole floor; left through its open RIGHT edge.
    rooms 11-15 water from here to the end; the level descends RIGHT, every
                left edge leading back up. Rooms 11-13's way on is a two-cell
                magma pillar in front of the right edge, which a stick takes.
    room 11     a twenty-cell magma wall over the water, crossed on the raft.
    rooms 12,14 the tentacles.
    room 15     the miner's room, the miner at x 128.
"""
