def test_the_tentacle_starts_at_the_heros_entry_x_clamped(env):
    """The level descends RIGHT: in by room 11's open right edge he appears
    on the LEFT of room 12 and the tentacle at its left clamp, 29; back up by
    room 13's left edge he appears on the right and it waits at 121."""
    import jax.numpy as jnp
    slot = _tentacle_slot(12)
    c = env.consts
    none = jnp.zeros_like(c.SPIDER_VALID[L - 1])
    s = _state(env, 11, player_x=jnp.int32(c.screen_width - 8 - c.player_width),
               player_y=jnp.int32(70), spider_alive=none)
    _obs, s, *_ = env.step(s, 3)                       # RIGHT, off the edge
    assert int(s.room) == 12 and int(s.tentacle_x[slot]) == 29
    s = _state(env, 13, player_x=jnp.int32(8), player_y=jnp.int32(70),
               spider_alive=none)
    _obs, s, *_ = env.step(s, 4)                       # LEFT, off the edge
    assert int(s.room) == 12 and int(s.tentacle_x[slot]) == 121


def test_the_engine_draws_the_tentacle_where_it_has_followed_him(env):
    import jax.numpy as jnp
    for room in TENTACLE_ROOMS:
        slot = _tentacle_slot(room)
        for x in (29, 77, 121):
            s = _state(env, room, player_x=jnp.int32(128),
                       player_y=jnp.int32(70), room_timer=jnp.int32(36),
                       tentacle_x=jnp.zeros_like(env.consts.SPIDER_VALID[L - 1],
                                                 dtype=jnp.int32).at[slot].set(x))
            frame = np.asarray(env.render(s))
            ys, xs = np.nonzero((frame == np.array(TENTACLE_BLUE)).all(axis=-1))
            assert xs.min() == x and ys.max() == 137, (room, x)


def test_the_tentacle_is_twelve_rows_tall_at_its_tallest(env):
    """Room 14's watch drew every pose two rows low; with the hero in the
    room both tentacles rise to row 126 at their tallest (measured)."""
    import jax.numpy as jnp
    for room in TENTACLE_ROOMS:
        slot = _tentacle_slot(room)
        tops = set()
        for t in range(64):
            s = _state(env, room, player_x=jnp.int32(128), player_y=jnp.int32(70),
                       room_timer=jnp.int32(t),
                       tentacle_x=jnp.zeros_like(env.consts.SPIDER_VALID[L - 1],
                                                 dtype=jnp.int32).at[slot].set(60))
            frame = np.asarray(env.render(s))
            ys, _xs = np.nonzero((frame == np.array(TENTACLE_BLUE)).all(axis=-1))
            if ys.size:
                tops.add(int(ys.min()))
        assert min(tops) == 126, room


