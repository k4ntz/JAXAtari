def test_the_engine_locks_the_untethered_spiders_pose_to_its_bob(env):
    """Pose 1 (legs gathered) exactly while it goes down, pose 0 while it
    comes back up, over a 16-frame cycle - as on the ROM (level 18's
    measurement; this level runs the same clock)."""
    import jax.numpy as jnp
    from jaxatari.games.jax_hero import _creature_pos
    c = env.consts
    slot = HL.SPIDERS[L - 1].index((2, 32, 65, 0, 4))
    got = []
    for t in range(32):
        _x, y = _creature_pos(c, jnp.int32(L - 1), jnp.int32(t))
        pose = (t // int(c.SPIDER_HOLD[L - 1][slot])) % 2   # 1 = _ART2
        got.append((int(y[slot]), pose))
    down = [p for (y0, p), (y1, _q) in zip(got, got[1:]) if y1 > y0]
    up = [p for (y0, p), (y1, _q) in zip(got, got[1:]) if y1 < y0]
    assert set(down) == {1} and set(up) == {0}
    assert {y for y, _p in got} == set(range(65, 73))
    assert got[:16] == got[16:], "a 16-frame cycle"


